  static List<NllbLanguage> get all => [
    for (final code in _codes) NllbLanguage(code, _label(code)),
  ];

  static String _label(String code) {
    final parts = code.split('_');
    final language = _names[parts.first] ?? parts.first.toUpperCase();
    final script = _scripts[parts.length > 1 ? parts[1] : ''];
    return script == null || script == 'Latin script'
        ? '$language (${parts.first})'
        : '$language · $script';
  }
